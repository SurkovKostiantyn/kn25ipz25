<?php
/**
 * Скрипт виходу з системи (деавторизації).
 * Повністю очищує сесію і перенаправляє на головну сторінку.
 */

// Відновлюємо доступ до поточної сесії
session_start();

// Очищає пам'ять масиву $_SESSION (всі змінні, що були збережені під час роботи)
session_unset();     

// Повністю знищує файл сесії на диску сервера, роблячи відновлення сесії неможливим
session_destroy();   

// Перенаправляємо користувача назад на головну сторінку
header('Location: index.php'); 

// Завжди робимо exit після header, щоб код нижче не виконувався
exit;
?>