<?php
/**
 * Секретний кабінет користувача.
 * Доступ сюди мають лише ті, хто успішно пройшов авторизацію.
 */
session_start();

// Перевіряємо, чи існує прапорець 'is_logged' і чи він не порожній
if (empty($_SESSION['is_logged'])) { 
    // Якщо користувач не авторизований, перенаправляємо його на головну сторінку (або login.php)
    header('Location: index.php');
    exit; // Обов'язкове завершення роботи скрипта після редиректу
}

// Читання кукі для отримання часу останнього входу
$lastLoginDate = "Невідомо";
if (isset($_COOKIE['user_time'])) {
    // Форматуємо мітка часу з кукі у читабельний вигляд
    $lastLoginDate = date('d.m.Y H:i:s', $_COOKIE['user_time']);
}
?>
<!DOCTYPE html>
<html lang="uk">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Особистий кабінет</title>
    <!-- Підключаємо загальні стилі -->
    <link rel="stylesheet" href="style.css">
</head>
<body>
    
    <?php 
    // Підключаємо файл навігації
    include 'navigation.php'; 
    ?>

    <h1>Особистий кабінет</h1>
    <p>Вітаємо в секретній зоні! Ви успішно пройшли перевірку даних.</p>
    
    <!-- Виводимо ID користувача з сесії -->
    <p>Ваш ID користувача: <strong><?= htmlspecialchars($_SESSION['uid'] ?? 'Невідомо') ?></strong></p>
    
    <!-- Виводимо дату останнього входу з кукі -->
    <p>Дата останнього входу: <strong><?= $lastLoginDate ?></strong></p>
    
    <hr>
    
    <h3>Інформація про сесію</h3>
    <p>
        Ця сторінка захищена від несанкціонованого доступу. Тільки авторизовані користувачі можуть її бачити. 
        Щоб завершити сеанс та вийти, скористайтеся кнопкою "Вихід" у навігаційному меню.
    </p>

</body>
</html>